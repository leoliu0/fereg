#!/usr/bin/env python3
"""Generate crates/fereg-core/src/iv/stock_yogo.rs from ivreg2's Stock-Yogo (2005) tables.

Source: `s_ivreg210_cdsy()` in ivreg210.ado (lines 618-742 of the version shipped with
ivreg2/ivreghdfe), the same tables ivreghdfe's `cdsy` reads from livreg2.mlib. Only the 2SLS
tables are emitted (IV relative bias 5/10/20/30 %: K1 <= 3; IV size 10/15/20/25 %: K1 <= 2);
rows are the number of excluded instruments L1 = 1..100.

Usage: python3 scripts/gen_stock_yogo.py [path/to/ivreg210.ado]
"""

import os
import re
import sys

TABLES = [  # (Mata name, columns, Rust const)
    ("ivbias5", 3, "IVBIAS5"),
    ("ivbias10", 3, "IVBIAS10"),
    ("ivbias20", 3, "IVBIAS20"),
    ("ivbias30", 3, "IVBIAS30"),
    ("ivsize10", 2, "IVSIZE10"),
    ("ivsize15", 2, "IVSIZE15"),
    ("ivsize20", 2, "IVSIZE20"),
    ("ivsize25", 2, "IVSIZE25"),
]


def parse(text, name, ncols):
    m = re.search(r"s_%s\s*=\s*\"([^\"]*)\"" % name, text)
    if not m:
        sys.exit(f"table s_{name} not found")
    # Mata: colshape(colshape(tokens(s), 2)[., 1], ncols) -- every other token is a value.
    toks = m.group(1).split()
    vals = toks[0::2]
    if len(vals) % ncols:
        sys.exit(f"table {name}: {len(vals)} values not a multiple of {ncols}")
    rows = [vals[i : i + ncols] for i in range(0, len(vals), ncols)]
    if len(rows) != 100:
        sys.exit(f"table {name}: expected 100 rows, got {len(rows)}")
    return rows


def lit(v):
    if v == ".":
        return "NA"
    x = float(v)
    s = repr(x)
    return s if ("." in s or "e" in s) else s + ".0"


def main():
    src = sys.argv[1] if len(sys.argv) > 1 else os.path.expanduser("~/ado/plus/i/ivreg210.ado")
    text = open(src, encoding="latin-1").read()
    out = [
        "//! Stock–Yogo (2005) critical values for the Cragg–Donald weak-identification test of 2SLS.",
        "//! GENERATED by `scripts/gen_stock_yogo.py` from ivreg2's `s_ivreg210_cdsy()` tables",
        "//! (ivreg210.ado). Do not edit by hand. Row = number of excluded instruments (1..=100),",
        "//! column = number of endogenous regressors; `NA` = no critical value.",
        "",
        "const NA: f64 = f64::NAN;",
        "",
    ]
    for name, ncols, const in TABLES:
        rows = parse(text, name, ncols)
        out.append(f"/// `{name}`")
        out.append(f"pub(crate) const {const}: [[f64; {ncols}]; 100] = [")
        for r in rows:
            out.append("    [" + ", ".join(lit(v) for v in r) + "],")
        out.append("];")
        out.append("")
    out += [
        "/// The 2SLS tables in ivreghdfe display order: (macro suffix, label, table accessor).",
        "pub(crate) const IV_TABLES: [(&str, &str, fn(usize, usize) -> f64); 8] = [",
    ]
    labels = {
        "ivbias5": " 5% maximal IV relative bias",
        "ivbias10": "10% maximal IV relative bias",
        "ivbias20": "20% maximal IV relative bias",
        "ivbias30": "30% maximal IV relative bias",
        "ivsize10": "10% maximal IV size",
        "ivsize15": "15% maximal IV size",
        "ivsize20": "20% maximal IV size",
        "ivsize25": "25% maximal IV size",
    }
    for name, ncols, const in TABLES:
        out.append(
            f'    ("{name}", "{labels[name]}", |l1, k1| if (1..=100).contains(&l1) && (1..={ncols}).contains(&k1) '
            f"{{ {const}[l1 - 1][k1 - 1] }} else {{ NA }}),"
        )
    out.append("];")
    out.append("")
    dst = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "crates", "fereg-core", "src", "iv", "stock_yogo.rs")
    with open(dst, "w") as f:
        f.write("\n".join(out))
    print(f"wrote {os.path.normpath(dst)}")


if __name__ == "__main__":
    main()
